"""Shared formatting for the paper tables in tables/."""
from __future__ import annotations

import csv
import hashlib
import json
import math
import os
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"
_CB_OUT = os.environ.get("CB_OUT")
_CB_TABLES = os.environ.get("CB_TABLES")
DERIVED = Path(_CB_OUT).resolve() if _CB_OUT else DATA
OUT_DIR = (Path(_CB_TABLES).resolve() if _CB_TABLES
           else DERIVED / "tables" if _CB_OUT else ROOT / "tables")
FIG_CODE = ROOT / "code" / "figures"
PREFIX = 12
MISSING = "--"
csv.field_size_limit(1 << 30)


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rel(path: Path) -> str:
    """Path relative to the repository; a $CB_OUT path is written as data/."""
    path = Path(path).resolve()
    if _CB_OUT and DERIVED in path.parents:
        return str(Path("data") / path.relative_to(DERIVED))
    return str(path.relative_to(ROOT))


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def read_json(path: Path):
    return json.loads(Path(path).read_text())


def read_jsonl(path: Path) -> list[dict]:
    with open(path) as fh:
        return [json.loads(x) for x in fh if x.strip()]


def number(x):
    """float, or None for an empty or non-numeric cell."""
    if x is None or x == "":
        return None
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(v) else v


def _sep(s: str) -> str:
    """Thousands separators and a minus sign for LaTeX text mode."""
    s = s.replace(",", "{,}")
    return "$-$" + s[1:] if s.startswith("-") else s


def count(x) -> str:
    v = number(x)
    return MISSING if v is None else _sep(f"{int(round(v)):,}")


def usd_m(x) -> str:
    """USD in millions, one decimal."""
    v = number(x)
    return MISSING if v is None else _sep(f"{v / 1e6:,.1f}")


def usd_k(x) -> str:
    """USD in thousands, no decimals."""
    v = number(x)
    return MISSING if v is None else _sep(f"{v / 1e3:,.0f}")


def pct(x, signed: bool = False) -> str:
    """A fraction as percent, one decimal."""
    v = number(x)
    if v is None:
        return MISSING
    return _sep(f"{100 * v:+.1f}" if signed else f"{100 * v:.1f}")


def millions(x) -> str:
    """A count in millions, one decimal (event counts)."""
    v = number(x)
    return MISSING if v is None else _sep(f"{v / 1e6:,.1f}")


def ratio(x, nd: int = 1) -> str:
    v = number(x)
    return MISSING if v is None else _sep(f"{v:,.{nd}f}")


def price(x) -> str:
    """A price in peg units, three decimals."""
    v = number(x)
    return MISSING if v is None else f"{v:.3f}"


def tex(s) -> str:
    """Escape text for LaTeX."""
    if s is None:
        return MISSING
    out = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"),
                 ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}")):
        out = out.replace(a, b)
    return out


def source_line(sources: list) -> str:
    """One comment line: each source with its sha256 prefix."""
    parts = []
    for s in sources:
        if isinstance(s, tuple):
            parts.append(f"{s[0]} ({s[1][:PREFIX]})")
        else:
            parts.append(f"{rel(s)} ({sha256(s)[:PREFIX]})")
    return "% Sources (sha256 prefix): " + "; ".join(parts)


def write(name: str, generator: str, sources: list, body: list[str]) -> Path:
    """tables/<name>.tex: the source line, a generator line, the tabular."""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    head = [source_line(sources),
            f"% Generated by {generator} (code/tables/build_all.py rebuilds all tables); do not edit."]
    path = OUT_DIR / f"{name}.tex"
    path.write_text("\n".join(head + body) + "\n")
    return path


def row(cells) -> str:
    return " & ".join(cells) + r" \\"


def notes(text: str, n_cols: int, width: int) -> list[str]:
    """Note rows under the bottom rule."""
    return [rf"\multicolumn{{{n_cols}}}{{l}}{{\footnotesize {line}}} \\"
            for line in textwrap.wrap(text, width, break_long_words=False, break_on_hyphens=False)]


